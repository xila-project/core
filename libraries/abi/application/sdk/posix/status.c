int xila_errno_from_status(XilaStatus status) {
    if (status == XILA_STATUS_OK)
        return 0;
    for (size_t index = 0; index < sizeof(status_map) / sizeof(status_map[0]); ++index) {
        if (status_map[index].status == status)
            return status_map[index].error;
    }
    return EIO;
}

int xila_fail(XilaStatus status) {
    errno = xila_errno_from_status(status);
    return -1;
}

int xila_fail_errno(int error) {
    errno = error;
    return -1;
}
