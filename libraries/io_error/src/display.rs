use core::fmt;
use embedded_i18n::t;

use crate::Kind;

impl fmt::Display for Kind {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        let message = match self {
            Self::InvalidArgument => t!("errors.invalid_argument"),
            Self::InvalidData => t!("errors.invalid_data"),
            Self::PermissionDenied => t!("errors.permission_denied"),
            Self::OperationNotPermitted => t!("errors.operation_not_permitted"),
            Self::InputOutput => t!("errors.input_output"),
            Self::OutOfMemory => t!("errors.out_of_memory"),
            Self::WouldBlock => t!("errors.would_block"),
            Self::ResourceBusy => t!("errors.resource_busy"),
            Self::Interrupted => t!("errors.interrupted"),
            Self::TimedOut => t!("errors.timed_out"),
            Self::Unsupported => t!("errors.unsupported"),
            Self::Overflow => t!("errors.overflow"),
            Self::WriteZero => t!("errors.write_zero"),
            Self::NoBuffers => t!("errors.no_buffers"),
            Self::NotFound => t!("errors.not_found"),
            Self::AlreadyExists => t!("errors.already_exists"),
            Self::InvalidFlags => t!("errors.invalid_flags"),
            Self::InvalidState => t!("errors.invalid_state"),
            Self::NotImplemented => t!("errors.not_implemented"),
            Self::ExecFormat => t!("errors.exec_format"),
            Self::NoChild => t!("errors.no_child"),
            Self::ArgumentListTooLong => t!("errors.argument_list_too_long"),
            Self::Deadlock => t!("errors.deadlock"),
            Self::BadDescriptor => t!("errors.bad_descriptor"),
            Self::InvalidPath => t!("errors.invalid_path"),
            Self::MissingPathComponent => t!("errors.missing_path_component"),
            Self::MissingFinalEntry => t!("errors.missing_final_entry"),
            Self::NameTooLong => t!("errors.name_too_long"),
            Self::SymlinkLoop => t!("errors.symlink_loop"),
            Self::NotADirectory => t!("errors.not_a_directory"),
            Self::IsADirectory => t!("errors.is_a_directory"),
            Self::DirectoryNotEmpty => t!("errors.directory_not_empty"),
            Self::NoSpace => t!("errors.no_space"),
            Self::FileTooLarge => t!("errors.file_too_large"),
            Self::ProcessFileLimit => t!("errors.process_file_limit"),
            Self::SystemFileLimit => t!("errors.system_file_limit"),
            Self::CrossDevice => t!("errors.cross_device"),
            Self::PathEscapesRoot => t!("errors.path_escapes_root"),
            Self::CorruptData => t!("errors.corrupt_data"),
            Self::MissingAttribute => t!("errors.missing_attribute"),
            Self::StaleHandle => t!("errors.stale_handle"),
            Self::ReadOnlyFileSystem => t!("errors.read_only_file_system"),
            Self::InvalidSeek => t!("errors.invalid_seek"),
            Self::DeviceUnavailable => t!("errors.device_unavailable"),
            Self::NoSuchTask => t!("errors.no_such_task"),
            Self::InappropriateIoControl => t!("errors.inappropriate_io_control"),
            Self::ConnectionRefused => t!("errors.connection_refused"),
            Self::ConnectionReset => t!("errors.connection_reset"),
            Self::ConnectionAborted => t!("errors.connection_aborted"),
            Self::NotConnected => t!("errors.not_connected"),
            Self::AlreadyConnected => t!("errors.already_connected"),
            Self::AddressInUse => t!("errors.address_in_use"),
            Self::AddressNotAvailable => t!("errors.address_not_available"),
            Self::DestinationRequired => t!("errors.destination_required"),
            Self::HostUnreachable => t!("errors.host_unreachable"),
            Self::NetworkUnreachable => t!("errors.network_unreachable"),
            Self::NetworkDown => t!("errors.network_down"),
            Self::BrokenPipe => t!("errors.broken_pipe"),
            Self::MessageTooLarge => t!("errors.message_too_large"),
            Self::DatagramTruncated => t!("errors.datagram_truncated"),
            Self::SocketOperationUnsupported => t!("errors.socket_operation_unsupported"),
            Self::ProtocolUnsupported => t!("errors.protocol_unsupported"),
            Self::AddressFamilyUnsupported => t!("errors.address_family_unsupported"),
            Self::InProgress => t!("errors.in_progress"),
            Self::AlreadyInProgress => t!("errors.already_in_progress"),
            Self::ProtocolError => t!("errors.protocol_error"),
            Self::NotASocket => t!("errors.not_a_socket"),
            Self::InvalidDnsName => t!("errors.invalid_dns_name"),
            Self::UnsupportedDnsQuery => t!("errors.unsupported_dns_query"),
            Self::NameNotResolved => t!("errors.name_not_resolved"),
            Self::ResolverTemporaryFailure => t!("errors.resolver_temporary_failure"),
            Self::ResolverFailure => t!("errors.resolver_failure"),
        };
        f.write_str(message)
    }
}
