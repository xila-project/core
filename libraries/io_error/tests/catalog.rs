    for (kind, id, errno, embedded) in rows {
        assert_ne!(id, 0);
        assert!(ids.insert(id));
        assert_eq!(kind.id(), id);
        assert_eq!(Kind::try_from(id), Ok(kind));
        assert_eq!(kind.posix_errno(), errno);
        assert_eq!(kind.kind(), embedded);
        assert!(!kind.to_string().is_empty());
    }
    for id in 0..=u16::MAX {
        assert_eq!(Kind::try_from(id).is_ok(), ids.contains(&id));
    }
